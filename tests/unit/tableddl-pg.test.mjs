import { describe, expect, it } from 'vitest'

import { alterTableStatements, createTableStatements } from '../../src/client/tableddl-pg.ts'
import { tableDraftFromDescription } from '../../src/client/tableddl.ts'

function column(overrides = {}) {
  return {
    name: 'id',
    typeName: 'integer',
    nullable: false,
    defaultValue: '',
    comment: '',
    autoIncrement: false,
    primaryKey: false,
    ...overrides,
  }
}

describe('createTableStatements', () => {
  it('creates identity columns, indexes, comments and foreign keys', () => {
    const statements = createTableStatements({
      schema: 'app',
      table: 'users',
      columns: [
        column({ name: 'id', autoIncrement: true, primaryKey: true }),
        column({ name: 'role_id', nullable: false }),
        column({ name: 'name', typeName: 'text', comment: 'display' }),
      ],
      indexes: [{ name: 'idx_name', unique: true, columns: ['name'] }],
      foreignKeys: [
        {
          name: 'fk_role',
          columns: ['role_id'],
          referencedSchema: 'app',
          referencedTable: 'roles',
          referencedColumns: ['id'],
          onDelete: 'CASCADE',
          onUpdate: 'RESTRICT',
        },
      ],
    })
    expect(statements).toEqual([
      [
        'CREATE TABLE "app"."users" (',
        '  "id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,',
        '  "role_id" integer NOT NULL,',
        '  "name" text NOT NULL,',
        '  PRIMARY KEY ("id"),',
        '  CONSTRAINT "fk_role" FOREIGN KEY ("role_id") REFERENCES "app"."roles" ("id") ON DELETE CASCADE ON UPDATE RESTRICT',
        ')',
      ].join('\n'),
      'CREATE UNIQUE INDEX "idx_name" ON "app"."users" ("name")',
      `COMMENT ON COLUMN "app"."users"."name" IS 'display'`,
    ])
  })
})

describe('alterTableStatements', () => {
  const description = {
    schema: 'app',
    table: 'orders',
    kind: 'table',
    columns: [
      column({ name: 'id', primaryKey: true }),
      column({ name: 'user_id' }),
      column({ name: 'note', typeName: 'text', comment: 'old' }),
    ],
    indexes: [
      { name: 'orders_pkey', columns: ['id'], unique: true, primary: true },
      { name: 'idx_user', columns: ['user_id'], unique: false },
    ],
    foreignKeys: [
      {
        name: 'fk_user',
        columns: ['user_id'],
        referencedSchema: 'app',
        referencedTable: 'users',
        referencedColumns: ['id'],
        onDelete: 'RESTRICT',
        onUpdate: 'RESTRICT',
      },
    ],
  }

  it('renames and adds columns, rebuilds indexes, changes FK rules and comments', () => {
    const original = tableDraftFromDescription(description)
    const next = tableDraftFromDescription(description)
    next.columns[1].name = 'buyer_id'
    next.columns[2].comment = 'new'
    next.columns.push(column({ name: 'amount', typeName: 'numeric(10,2)', nullable: true, defaultValue: '0' }))
    next.indexes[0].unique = true
    next.foreignKeys[0].onDelete = 'CASCADE'

    expect(alterTableStatements(original, next)).toEqual([
      'ALTER TABLE "app"."orders" DROP CONSTRAINT "fk_user"',
      'DROP INDEX "app"."idx_user"',
      'ALTER TABLE "app"."orders" RENAME COLUMN "user_id" TO "buyer_id"',
      'ALTER TABLE "app"."orders" ADD COLUMN "amount" numeric(10,2) DEFAULT 0',
      'CREATE UNIQUE INDEX "idx_user" ON "app"."orders" ("buyer_id")',
      'ALTER TABLE "app"."orders" ADD CONSTRAINT "fk_user" FOREIGN KEY ("buyer_id") REFERENCES "app"."users" ("id") ON DELETE CASCADE ON UPDATE RESTRICT',
      `COMMENT ON COLUMN "app"."orders"."note" IS 'new'`,
    ])
  })

  it('drops and re-adds the primary key using the constraint name', () => {
    const original = tableDraftFromDescription(description)
    const next = tableDraftFromDescription(description)
    next.columns[0].primaryKey = false
    next.columns[1].primaryKey = true
    expect(alterTableStatements(original, next)).toEqual([
      'ALTER TABLE "app"."orders" DROP CONSTRAINT "orders_pkey"',
      'ALTER TABLE "app"."orders" ADD PRIMARY KEY ("user_id")',
    ])
  })

  it('changes type, nullability, default and identity with ALTER COLUMN clauses', () => {
    const original = tableDraftFromDescription(description)
    const next = tableDraftFromDescription(description)
    next.columns[1].typeName = 'bigint'
    next.columns[1].nullable = true
    next.columns[2].defaultValue = `'hello'::text`
    next.columns[0].autoIncrement = false
    expect(alterTableStatements(original, next)).toEqual([
      'ALTER TABLE "app"."orders"\n  ALTER COLUMN "user_id" TYPE bigint,\n  ALTER COLUMN "user_id" DROP NOT NULL',
      'ALTER TABLE "app"."orders"\n  ALTER COLUMN "note" SET DEFAULT \'hello\'::text',
    ])
  })
})