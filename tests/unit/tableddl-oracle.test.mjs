import { describe, expect, it } from 'vitest'

import { tableDraftFromDescription } from '../../src/client/tableddl.ts'
import {
  alterOracleTableStatements,
  createOracleTableStatements,
  validateOracleDraft,
} from '../../src/client/tableddl-oracle.ts'

function column(overrides) {
  return {
    name: 'ID',
    typeName: 'NUMBER(10)',
    nullable: false,
    defaultValue: '',
    comment: '',
    autoIncrement: false,
    primaryKey: false,
    ...overrides,
  }
}

function draft(overrides = {}) {
  return { schema: 'APP', table: 'USERS', columns: [column({ primaryKey: true })], indexes: [], foreignKeys: [], ...overrides }
}

describe('Oracle table DDL', () => {
  it('renders identity, comments, indexes and a foreign key without ON UPDATE', () => {
    const statements = createOracleTableStatements(
      draft({
        columns: [
          column({ name: 'ID', primaryKey: true, autoIncrement: true }),
          column({ name: 'NAME', typeName: 'VARCHAR2(100)', comment: "owner's name" }),
        ],
        indexes: [{ name: 'IDX_USERS_NAME', unique: true, columns: ['NAME'] }],
        foreignKeys: [
          {
            name: 'FK_USERS_TEAM',
            columns: ['NAME'],
            referencedSchema: 'APP',
            referencedTable: 'TEAMS',
            referencedColumns: ['NAME'],
            onDelete: 'SET NULL',
            onUpdate: 'CASCADE',
          },
        ],
      }),
    )
    expect(statements[0]).toBe(
      [
        'CREATE TABLE "APP"."USERS" (',
        '  "ID" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
        '  "NAME" VARCHAR2(100) NOT NULL,',
        '  CONSTRAINT "PK_USERS" PRIMARY KEY ("ID"),',
        '  CONSTRAINT "FK_USERS_TEAM" FOREIGN KEY ("NAME") REFERENCES "APP"."TEAMS" ("NAME") ON DELETE SET NULL',
        ')',
      ].join('\n'),
    )
    expect(statements[1]).toBe('CREATE UNIQUE INDEX "APP"."IDX_USERS_NAME" ON "APP"."USERS" ("NAME")')
    expect(statements[2]).toBe('COMMENT ON COLUMN "APP"."USERS"."NAME" IS \'owner\'\'s name\'')
  })

  it('alters columns, comments and indexes', () => {
    const description = {
      schema: 'APP',
      table: 'USERS',
      kind: 'table',
      columns: [
        column({ name: 'ID', primaryKey: true }),
        column({ name: 'NAME', typeName: 'VARCHAR2(50)', defaultValue: "'x'", comment: 'old' }),
      ],
      indexes: [
        { name: 'PK_USERS', columns: ['ID'], unique: true, primary: true, constraint: true },
        { name: 'IDX_NAME', columns: ['ID'], unique: false },
      ],
    }
    const original = tableDraftFromDescription(description)
    const next = tableDraftFromDescription(description)
    next.columns[1].typeName = 'VARCHAR2(100)'
    next.columns[1].defaultValue = ''
    next.columns[1].comment = 'new'
    next.indexes[0].columns = ['NAME']

    const statements = alterOracleTableStatements(original, next)
    expect(statements[0]).toBe('DROP INDEX "APP"."IDX_NAME"')
    expect(statements[1]).toBe('ALTER TABLE "APP"."USERS" MODIFY ("NAME" VARCHAR2(100) DEFAULT NULL)')
    expect(statements[2]).toBe('CREATE INDEX "APP"."IDX_NAME" ON "APP"."USERS" ("NAME")')
    expect(statements[3]).toBe('COMMENT ON COLUMN "APP"."USERS"."NAME" IS \'new\'')
  })

  it('renames a column and preserves the primary key constraint', () => {
    const description = {
      schema: 'APP',
      table: 'USERS',
      kind: 'table',
      columns: [column({ name: 'ID', primaryKey: true }), column({ name: 'NAME', typeName: 'VARCHAR2(50)' })],
      indexes: [{ name: 'PK_USERS', columns: ['ID'], unique: true, primary: true, constraint: true }],
    }
    const original = tableDraftFromDescription(description)
    const next = tableDraftFromDescription(description)
    next.columns[1].name = 'DISPLAY_NAME'
    const statements = alterOracleTableStatements(original, next)
    expect(statements).toEqual(['ALTER TABLE "APP"."USERS" RENAME COLUMN "NAME" TO "DISPLAY_NAME"'])
  })

  it('allows only one identity column', () => {
    expect(validateOracleDraft(draft())).toBeNull()
    expect(
      validateOracleDraft(
        draft({ columns: [column({ autoIncrement: true }), column({ name: 'B', autoIncrement: true })] }),
      ),
    ).toBe('auto-increment')
  })
})